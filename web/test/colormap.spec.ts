// The browser views' colour index (lutIndex) against the native reference,
// map_f32_to_rgba8 (src/host/tensor_bridge.cpp), on a table it produced
// (fixtures/lut_index.json, made by fixtures/make_lut_index.py): increasing,
// decreasing and zero-width ranges, ranges with an infinite or NaN end or an
// infinite width, and values at index boundaries, NaN, the infinities, zeros
// and subnormals. The threshold search the WebGPU shaders do, and the Canvas 2D
// heatmap's colormapInto, must give the same index for every case.
//
// Then the Canvas 2D fallback's colormap against vectors generated by the C++: lutIndex (the points
// view) and colormapInto (the heatmap and image renderer) give every boundary input of every
// range the RGBA that the reference map_f32_to_rgba8 gives it. The file is the one that
// caliper_colormap_cases writes, named by CALIPER_COLORMAP_CASES; without it the test is skipped.
// It needs no browser, so it runs once, in the canvas2d project.

import fs from 'node:fs';
import path from 'node:path';
import { colormapLut, colormapThresholds, lutIndex, thresholdIndex } from '../src/render/colormap.js';
import { colormapInto } from '../src/render/heatmap-2d.js';
import { readColormapCases } from './colormap_cases.js';
import { expect, test, WEB } from './util.js';

const table = JSON.parse(fs.readFileSync(path.join(WEB, 'test', 'fixtures', 'lut_index.json'), 'utf8')) as {
  cases: [string, string, string, number][];
};
const dv = new DataView(new ArrayBuffer(4));
const flt = (hex: string) => {
  dv.setUint32(0, parseInt(hex, 16));
  return dv.getFloat32(0);
};
const cases = table.cases.map(([v, lo, hi, idx]) => ({ v: flt(v), lo: flt(lo), hi: flt(hi), idx, key: `${v} ${lo} ${hi}` }));

test('lutIndex gives the native reference index for every case of the table', () => {
  expect(cases.length).toBeGreaterThan(500);
  const wrong = cases.filter((c) => lutIndex(c.v, c.lo, c.hi) !== c.idx).map((c) => `${c.key}: ${lutIndex(c.v, c.lo, c.hi)} != ${c.idx}`);
  expect(wrong).toEqual([]);
});

test('the WebGPU shaders\' threshold search and the Canvas 2D heatmap give the same indices', () => {
  const ranges = new Map<string, typeof cases>();
  for (const c of cases) {
    const k = c.key.split(' ').slice(1).join(' ');
    if (!ranges.has(k)) ranges.set(k, []);
    ranges.get(k)!.push(c);
  }
  const lut = colormapLut('magma');
  const wrong: string[] = [];
  for (const group of ranges.values()) {
    const { lo, hi } = group[0];
    const th = colormapThresholds(lo, hi);
    for (const c of group) {
      const got = thresholdIndex(c.v, th);
      if (got !== c.idx) wrong.push(`thresholds ${c.key}: ${got} != ${c.idx}`);
    }
    const data = new Float32Array(group.map((c) => c.v));
    const out = new Uint8ClampedArray(data.length * 4);
    colormapInto(out, data, lo, hi, lut);
    group.forEach((c, i) => {
      const want = [...lut.subarray(c.idx * 4, c.idx * 4 + 3), 255];
      const got = [...out.subarray(i * 4, i * 4 + 4)];
      if (got.join() !== want.join()) wrong.push(`colormapInto ${c.key}: ${got} != ${want}`);
    });
  }
  expect(wrong).toEqual([]);
});

const CASES = process.env.CALIPER_COLORMAP_CASES;

test('the Canvas 2D colormap matches the C++ reference on every boundary input', async ({}, info) => {
  test.skip(info.project.name !== 'canvas2d', 'no browser needed: runs once');
  test.skip(!CASES, 'needs CALIPER_COLORMAP_CASES, the file that caliper_colormap_cases writes');
  const cases = readColormapCases(CASES!);
  let total = 0;
  const bad: string[] = [];
  for (const c of cases) {
    const values = new Float32Array(c.inputs.buffer.slice(c.inputs.byteOffset, c.inputs.byteOffset + c.inputs.length));
    // colormapInto takes the table as RGBA bytes.
    const lut = new Uint8Array(c.table.buffer.slice(0));
    const out = new Uint8ClampedArray(values.length * 4);
    colormapInto(out, values, c.vmin, c.vmax, lut);
    for (let i = 0; i < values.length; i++) {
      const want = c.expected[i];
      const k = lutIndex(values[i], c.vmin, c.vmax);
      const viaIndex = c.table[k];
      // colormapInto writes alpha 255; compare its RGB with the reference's.
      const viaInto = (out[4 * i] | (out[4 * i + 1] << 8) | (out[4 * i + 2] << 16)) >>> 0;
      const bits = c.inputs.readUInt32LE(4 * i).toString(16);
      if (viaIndex !== want && bad.length < 8) bad.push(`${c.name}: lutIndex(0x${bits}) = ${k}, want 0x${want.toString(16)}`);
      if (viaInto !== (want & 0xffffff) && bad.length < 8) bad.push(`${c.name}: colormapInto(0x${bits}) = 0x${viaInto.toString(16)}`);
    }
    total += values.length;
  }
  console.log(`[canvas2d] lutIndex and colormapInto: ${total} inputs over ${cases.length} ranges from the C++, ${bad.length} differ`);
  expect(bad).toEqual([]);
});
