// The generated shader programs (src/host/gfx/shaders/generated) in headless Chromium, with raw
// WebGPU and no view code: every program compiles and every compute entry and checked pair
// becomes a pipeline with the program's explicit layouts, on a default device and on a
// compatibility-mode device; the colormap by keys matches the C++ byte for byte on both, through
// the colormap probe, the texture path's compute form (colormap_texture) and the vertex stage of
// a points draw; and the points, segment and mesh programs draw a small fixture, read back as PNGs.
//
// The colormap's cases are vectors generated by the C++: the file that caliper_colormap_cases
// writes, named by CALIPER_COLORMAP_CASES, holds for each boundary range the Cmap block from the
// shared derivation (src/host/gfx/colormap_keys.h), the inputs, and the RGBA that the reference
// map_f32_to_rgba8 gives each. Without the file the colormap rows and the capture, whose keys
// come from it too, are skipped.

import fs from 'node:fs';
import path from 'node:path';
import { type ColormapCase, readColormapCases } from './colormap_cases.js';
import { expect, REPO, serve, test } from './util.js';

const GEN = path.join(REPO, 'src', 'host', 'gfx', 'shaders', 'generated');
type Prog = { name: string; test_only: boolean; pairs: [string, string][]; bindings: unknown[]; entries: { name: string; stage: string }[] };
const listing = JSON.parse(fs.readFileSync(path.join(GEN, 'programs.json'), 'utf8')) as { naga: string; programs: Prog[] };
const programs = Object.fromEntries(listing.programs.map((p) => [p.name, p]));
// The WGSL of each program, read from the raw string pieces of its generated header.
const codes = Object.fromEntries(listing.programs.map((p) => {
  const h = fs.readFileSync(path.join(GEN, `${p.name}_wgsl.h`), 'utf8');
  return [p.name, [...h.matchAll(/R"wgsl\(([\s\S]*?)\)wgsl"/g)].map((m) => m[1]).join('')];
}));

// ---- colormap cases ------------------------------------------------------------------------

const CASES = process.env.CALIPER_COLORMAP_CASES;
const NO_CASES = 'needs CALIPER_COLORMAP_CASES, the file that caliper_colormap_cases writes';
const cases = CASES ? readColormapCases(CASES) : [];

/** Pads a case's inputs with +0 to whole rows of 256, the expected with +0's colour (input 0). */
function rows256(c: ColormapCase): { inputs: Buffer; expected: Uint32Array; rows: number } {
  const n = Math.ceil(c.inputs.length / 4 / 256) * 256;
  const inputs = Buffer.alloc(4 * n);
  c.inputs.copy(inputs);
  const expected = new Uint32Array(n).fill(c.expected[0]);
  expected.set(c.expected);
  return { inputs, expected, rows: n / 256 };
}

// ---- the tests -----------------------------------------------------------------------------

test.describe('generated shader programs', () => {
  let origin = '';
  let close = () => {};
  test.beforeAll(async () => { ({ origin, close } = await serve(REPO)); });
  test.afterAll(() => close());

  test.beforeEach(async ({ page }, info) => {
    test.skip(info.project.name === 'canvas2d', 'needs WebGPU');
    await page.goto(`${origin}/web/test/blank.html`);
    await page.addScriptTag({ url: `${origin}/web/test/shaders_page.js` });
  });

  for (const level of ['default', 'compatibility'] as const) {
    test(`every program compiles and every pipeline is created on a ${level} device`, async ({ page }, info) => {
      const r = await page.evaluate(async ({ level, programs, codes }) => {
        const c = (window as any).shaderCheck;
        const d = await c.device(level);
        const out: { messages: string[]; pipelines: number; expected: number } = { messages: [], pipelines: 0, expected: 0 };
        for (const p of Object.values(programs) as any[]) {
          const one = await c.compileProgram(d.dev, p, codes[p.name]);
          out.messages.push(...one.messages); out.pipelines += one.pipelines; out.expected += one.expected;
        }
        return { ...out, adapter: d.adapter, core: d.core, fallback: d.fallback };
      }, { level, programs, codes });
      console.log(`[${info.project.name}] ${level}: ${r.adapter}${r.fallback ? ' (fallback)' : ''}, core features ${r.core}: `
                  + `${Object.keys(programs).length} programs, ${r.pipelines} of ${r.expected} pipelines, ${r.messages.length} messages`);
      expect(r.core).toBe(level === 'default');
      expect(r.messages).toEqual([]);
      expect(r.pipelines).toBe(r.expected);
    });

    // The three forms of the colormap by keys: the probe (a storage buffer), the texture path's
    // compute form (an rgba8unorm storage texture) and the vertex stage of a points draw (one
    // point a pixel wide on each pixel centre), each against the C++ byte for byte.
    for (const form of ['probe', 'texture'] as const) {
      test(`the colormap by keys matches the C++ byte for byte through the ${form} on a ${level} device`, async ({ page }, info) => {
        test.skip(!CASES, NO_CASES);
        test.setTimeout(240_000);
        let total = 0, bad = 0;
        const first: string[] = [];
        for (const c of cases) {
          const { inputs, expected } = form === 'probe' ? c : rows256(c);
          const got64 = await page.evaluate(async ({ level, form, progs, codes, block, inputs }) => {
            const s = (window as any).shaderCheck;
            const d = await s.device(level);
            if (form === 'probe') return s.colormap(d.dev, progs.colormap_probe, codes.colormap_probe, block, inputs);
            return s.colormapTexture(d.dev, progs.colormap_texture, codes.colormap_texture, block, inputs);
          }, { level, form, progs: { colormap_probe: programs.colormap_probe, colormap_texture: programs.colormap_texture },
               codes: { colormap_probe: codes.colormap_probe, colormap_texture: codes.colormap_texture },
               block: c.block.toString('base64'), inputs: inputs.toString('base64') });
          const g = Buffer.from(got64, 'base64');
          const got = new Uint32Array(g.buffer, g.byteOffset, g.length / 4);
          expect(got.length, c.name).toBe(expected.length);
          for (let i = 0; i < got.length; i++) {
            if (got[i] !== expected[i]) {
              if (bad++ < 5) first.push(`${c.name}: input 0x${inputs.readUInt32LE(4 * i).toString(16)} got 0x${got[i].toString(16)} want 0x${expected[i].toString(16)}`);
            }
          }
          total += got.length;
        }
        console.log(`[${info.project.name}] ${level}, ${form}: ${total} inputs over ${cases.length} ranges from the C++, ${bad} differ`);
        expect(first).toEqual([]);
        expect(bad).toBe(0);
      });
    }
  }

});
