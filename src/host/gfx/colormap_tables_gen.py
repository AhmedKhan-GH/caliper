#!/usr/bin/env python3
"""Generates colormap_tables.h, the twelve added colormaps of the graphics layer.

Usage: python colormap_tables_gen.py [output.h] [--samples]
  The default output is colormap_tables.h beside this script.
  --samples prints entries 0, 64, 128, 191 and 255 of each map, for the tests.

Each map is sampled at 256 evenly spaced points, i / 255 for i in 0 to 255. Each
channel is scaled by 255 and rounded to 8 bits with round half to even (numpy
rint). The entry packs r | g << 8 | b << 16 | 0xff << 24.
Needs matplotlib 3.10 or newer and cmcrameri.
"""
import os
import sys

import numpy as np
import matplotlib
import cmcrameri
from matplotlib import colormaps as mpl_maps
from cmcrameri import cm as crameri

MATPLOTLIB = ["cividis", "inferno", "plasma", "turbo", "twilight", "coolwarm"]
CRAMERI = ["batlow", "vik", "roma", "oslo", "lajolla", "berlin"]
NAMES = MATPLOTLIB + CRAMERI   # ids 4 to 15


def table(name):
    cmap = mpl_maps[name] if name in MATPLOTLIB else getattr(crameri, name)
    rgb = np.asarray(cmap(np.arange(256) / 255.0))[:, :3]
    b = np.rint(rgb * 255.0).astype(np.uint32)
    return [int(r | (g << 8) | (bl << 16) | (0xff << 24)) for r, g, bl in b]


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    tables = {n: table(n) for n in NAMES}
    if "--samples" in sys.argv:
        for n in NAMES:
            print(n, " ".join("%d:0x%08x" % (i, tables[n][i]) for i in (0, 64, 128, 191, 255)))
        return
    out = args[0] if args else os.path.join(os.path.dirname(os.path.abspath(__file__)), "colormap_tables.h")
    L = []
    L.append("// colormap_tables.h: the built-in colormap tables of the graphics layer, ids 0 to 15.")
    L.append("//")
    L.append("// Generated by colormap_tables_gen.py; do not edit by hand. Ids 0 to 2 (viridis, magma, rdbu)")
    L.append("// come from caliper_host::colormap_lut, and id 3 (greys) is the grey ramp. Ids 4 to 15 are")
    L.append("// the tables below, in the order of the spec's name table: cividis, inferno, plasma, turbo,")
    L.append("// twilight, coolwarm, batlow, vik, roma, oslo, lajolla, berlin.")
    L.append("//")
    L.append("// Sources: cividis, inferno, plasma, turbo, twilight and coolwarm come from matplotlib %s." % matplotlib.__version__)
    L.append("// batlow, vik, roma, oslo, lajolla and berlin come from the cmcrameri package %s, which" % cmcrameri.__version__)
    L.append("// ships the Scientific Colour Maps. Each map is sampled at 256 evenly")
    L.append("// spaced points, i / 255 for i in 0 to 255. Each channel is rounded to 8 bits with round")
    L.append("// half to even. An entry packs r | g << 8 | b << 16 | 0xff << 24.")
    L.append("#pragma once")
    L.append("")
    L.append('#include "tensor_bridge.h"   // caliper_host::colormap_lut and CALIPER_CMAP_*')
    L.append("")
    L.append("#include <cstdint>")
    L.append("")
    L.append("namespace caliper_gfx {")
    L.append("namespace cmap {")
    L.append("")
    L.append("// The number of built-in colormaps, ids 0 to kBuiltinColormaps - 1.")
    L.append("inline constexpr int kBuiltinColormaps = 16;")
    L.append("")
    for i, n in enumerate(NAMES):
        L.append("// Id %d, %s: 256 packed RGBA8 entries." % (i + 4, n))
        L.append("inline constexpr uint32_t k_%s[256] = {" % n)
        for r in range(0, 256, 8):
            L.append("    " + ", ".join("0x%08x" % v for v in tables[n][r:r + 8]) + ",")
        L.append("};")
        L.append("")
    L.append("// The 256-entry table of a built-in colormap id, or nullptr for an id outside 0 to 15.")
    L.append("// Ids 0 to 2 are the host's viridis, magma and rdbu, id 3 is greys, ids 4 to 15 are the")
    L.append("// tables above.")
    L.append("inline const uint32_t* builtin_lut(int32_t id) {")
    L.append("    static const struct Greys {")
    L.append("        uint32_t t[256];")
    L.append("        Greys() { for (uint32_t i = 0; i < 256; ++i) t[i] = 0xff000000u | (i << 16) | (i << 8) | i; }")
    L.append("    } greys;")
    L.append("    switch (id) {")
    L.append("        case 0: return caliper_host::colormap_lut(CALIPER_CMAP_VIRIDIS);")
    L.append("        case 1: return caliper_host::colormap_lut(CALIPER_CMAP_MAGMA);")
    L.append("        case 2: return caliper_host::colormap_lut(CALIPER_CMAP_RDBU);")
    L.append("        case 3: return greys.t;")
    for i, n in enumerate(NAMES):
        L.append("        case %d: return k_%s;" % (i + 4, n))
    L.append("        default: return nullptr;")
    L.append("    }")
    L.append("}")
    L.append("")
    L.append("}  // namespace cmap")
    L.append("}  // namespace caliper_gfx")
    with open(out, "w") as f:
        f.write("\n".join(L) + "\n")


main()
