#!/usr/bin/env python3
"""Generates the graphics layer's shader outputs from the WGSL sources.

    python3 tools/shaders/generate.py           write src/host/gfx/shaders/generated/
    python3 tools/shaders/generate.py --check   regenerate and fail on any difference

For each program of src/host/gfx/shaders/manifest.json it concatenates the program's WGSL
sources, translates the result with the pinned Naga (through tools/shaders/naga-driver, which
passes Caliper's Metal binding map), and writes into src/host/gfx/shaders/generated/:

    <program>_wgsl.h    the assembled WGSL, which the browser and Dawn compile
    <program>_msl.h     the MSL, which the Metal backend compiles at run time
    <program>_spv.h     the SPIR-V words, which the Vulkan backend loads
    uniforms.h          every uniform block as a C++ struct with static_asserted size and offsets
    programs.h          the program ids and each program's entries and bindings (gfx.h's
                        EntryDesc and BindingDesc), its vertex inputs and its checked pairs
    programs_metal.h, programs_vulkan.h, programs_webgpu.h
                        the table of ProgramDescs for one backend, indexed by program id
    programs.json       the same description for tools and tests outside C++

An output a program marks as hand-written is not generated; the backend's table includes the
hand-written header instead, which defines the same constant. Every file is a function of
the sources, the manifest and the Naga version, with no time stamp or local path, so the
check can compare bytes. The driver is built with cargo on first use (Rust is needed only
here); --driver names a built one.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DRIVER = REPO / "tools" / "shaders" / "naga-driver"
SHADERS = GENERATED = MANIFEST = Path()


def set_root(root: Path) -> None:
    """Points the generator at a repository root (a copy, in the generator's own test)."""
    global REPO, SHADERS, GENERATED, MANIFEST
    REPO = root
    SHADERS = root / "src" / "host" / "gfx" / "shaders"
    GENERATED = SHADERS / "generated"
    MANIFEST = SHADERS / "manifest.json"


set_root(REPO)
OUTPUTS = ("wgsl", "msl", "spirv")
PIECE = 12000  # bytes per raw string literal piece, below MSVC's 16,380
NAMESPACE = "caliper_gfx::shaders"


class Error(Exception):
    pass


def camel(name: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in name.split("_"))


def naga_version() -> str:
    lock = (DRIVER / "Cargo.lock").read_text()
    m = re.search(r'\[\[package\]\]\nname = "naga"\nversion = "([^"]+)"', lock)
    if not m:
        raise Error("naga is not in tools/shaders/naga-driver/Cargo.lock")
    return m.group(1)


def build_driver() -> Path:
    target = Path(os.environ.get("CARGO_TARGET_DIR", DRIVER / "target"))
    subprocess.run(["cargo", "build", "--release", "--locked", "--quiet",
                    "--manifest-path", str(DRIVER / "Cargo.toml"), "--target-dir", str(target)], check=True)
    exe = target / "release" / ("caliper-naga-driver.exe" if os.name == "nt" else "caliper-naga-driver")
    if not exe.exists():
        raise Error(f"the driver was not built at {exe}")
    return exe


# ---- C++ text ------------------------------------------------------------------------------

def banner(program: dict | None, version: str, what: str) -> str:
    lines = ["// Generated by tools/shaders/generate.py. Do not edit: change the WGSL sources or",
             "// src/host/gfx/shaders/manifest.json and run the generator again.", "//"]
    if program is not None:
        lines.append(f"// {what} of the program {program['name']}, assembled from")
        for s in program["sources"]:
            lines.append(f"//   src/host/gfx/shaders/{s}")
    else:
        lines.append(f"// {what}")
    lines.append(f"// Translated with Naga {version}.")
    return "\n".join(lines) + "\n"


def raw_string(text: str, tag: str) -> str:
    """text as adjacent raw string literals, split at line ends into pieces of at most PIECE bytes."""
    if f"){tag}\"" in text:
        raise Error(f"the text contains the raw string delimiter ){tag}\"")
    pieces, cur = [], ""
    for line in text.splitlines(keepends=True):
        if cur and len((cur + line).encode()) > PIECE:
            pieces.append(cur)
            cur = ""
        cur += line
    if cur:
        pieces.append(cur)
    return "\n".join(f'R"{tag}({p}){tag}"' for p in pieces)


def source_header(program: dict, version: str, kind: str, payload) -> str:
    const = f"k{camel(program['name'])}{ {'wgsl': 'Wgsl', 'msl': 'Msl', 'spirv': 'Spirv'}[kind] }"
    what = {"wgsl": "The WGSL", "msl": "The MSL", "spirv": "The SPIR-V"}[kind]
    out = [banner(program, version, what), "#pragma once\n"]
    if kind == "spirv":
        out.append("#include <cstdint>\n")
        out.append(f"namespace {NAMESPACE} {{\n")
        out.append(f"// {len(payload)} words, little-endian, SPIR-V version from the generator.")
        out.append(f"inline constexpr uint32_t {const}[] = {{")
        for i in range(0, len(payload), 8):
            out.append("    " + ", ".join(f"0x{w:08x}" for w in payload[i:i + 8]) + ",")
        out.append("};\n")
    else:
        tag = kind
        out.append(f"namespace {NAMESPACE} {{\n")
        out.append(f"inline constexpr char {const}[] =\n{raw_string(payload, tag)};\n")
    out.append(f"}}  // namespace {NAMESPACE}\n")
    return "\n".join(out)


CTYPE = {"f32": "float", "u32": "uint32_t", "i32": "int32_t"}


def struct_decl(block: dict, structs: dict[str, str], order: list[str]) -> str:
    """Declares the struct of a uniform block (and the structs it contains) in structs, in order."""
    name = block["name"]
    if name in structs:
        return name
    fields, asserts, cur = [], [], 0
    for m in sorted(block["members"], key=lambda m: m["offset"]):
        off, t = m["offset"], m["type"]
        if off > cur:
            fields.append(f"    uint8_t gap_{cur}_[{off - cur}];")
        decl, size = member_decl(m["name"], t, structs, order)
        fields.append(f"    {decl};  // {off}")
        asserts.append(f"static_assert(offsetof({name}, {m['name']}) == {off}, \"{name}::{m['name']}\");")
        cur = off + size
    if block["size"] > cur:
        fields.append(f"    uint8_t gap_{cur}_[{block['size'] - cur}];")
    text = (f"struct alignas(16) {name} {{\n" + "\n".join(fields) + "\n};\n"
            f"static_assert(sizeof({name}) == {block['size']}, \"{name}\");\n" + "\n".join(asserts) + "\n")
    structs[name] = text
    order.append(name)
    return name


def member_decl(name: str, t: dict, structs: dict[str, str], order: list[str]) -> tuple[str, int]:
    k = t["kind"]
    if k == "scalar":
        return f"{CTYPE[t['scalar']]} {name}", 4
    if k == "vector":
        return f"{CTYPE[t['scalar']]} {name}[{t['count']}]", 4 * t["count"]
    if k == "matrix":
        if t["rows"] == 3:  # each column padded to four components
            return f"{CTYPE[t['scalar']]} {name}[{t['columns']}][4]", t["size"]
        return f"{CTYPE[t['scalar']]} {name}[{t['columns'] * t['rows']}]", t["size"]
    if k == "struct":
        return f"{struct_decl(t, structs, order)} {name}", t["size"]
    if k == "array":
        e, n, stride = t["element"], t["count"], t["stride"]
        if n == 0:
            raise Error(f"{name}: a runtime-sized array in a uniform block")
        if e["kind"] == "scalar" and stride == 4:
            return f"{CTYPE[e['scalar']]} {name}[{n}]", t["size"]
        if e["kind"] == "scalar" and stride == 16:
            return f"{CTYPE[e['scalar']]} {name}[{n}][4]", t["size"]  # element i is [i][0]
        if e["kind"] == "vector" and stride == 4 * e["count"]:
            return f"{CTYPE[e['scalar']]} {name}[{n}][{e['count']}]", t["size"]
        if e["kind"] == "vector" and e["count"] == 3 and stride == 16:
            return f"{CTYPE[e['scalar']]} {name}[{n}][4]", t["size"]
        if e["kind"] == "struct" and stride == e["size"]:
            return f"{struct_decl(e, structs, order)} {name}[{n}]", t["size"]
        raise Error(f"{name}: an array layout the generator does not map to C++")
    raise Error(f"{name}: a {k} member in a uniform block")


VERTEX_FORMAT = {"f32": "F32", "vec2<f32>": "F32x2", "vec3<f32>": "F32x3", "vec4<f32>": "F32x4",
                 "u32": "U32", "i32": "S32", "vec2<u32>": "U32x2"}
OUTPUT_FORMAT = {"vec4<f32>": "RGBA8Unorm", "vec2<u32>": "RG32Uint", "u32": "R32Uint", "f32": "R32Float"}
STAGE = {"vertex": "kStageVertex", "fragment": "kStageFragment", "compute": "kStageCompute"}
FORMAT = {"Rgba8Unorm": "RGBA8Unorm", "Bgra8Unorm": "BGRA8Unorm", "R8Unorm": "R8Unorm", "R16Uint": "R16Uint",
          "R32Uint": "R32Uint", "Rg32Uint": "RG32Uint", "R32Float": "R32Float"}


def programs_header(programs: list[dict], descs: dict[str, dict], version: str) -> str:
    out = [banner(None, version, "The programs of the graphics layer: their ids, entries, bindings, vertex inputs and checked pairs."),
           "#pragma once\n", '#include "gfx/gfx.h"', '#include "gfx/shaders/generated/uniforms.h"\n',
           "#include <cstdint>\n", f"namespace {NAMESPACE} {{\n",
           "// A program's id is its index in the tables of programs_metal.h, programs_vulkan.h and",
           "// programs_webgpu.h.", "enum class ProgramId : uint32_t {"]
    for i, p in enumerate(programs):
        note = "  // test only" if p.get("test_only") else ""
        out.append(f"    {p['name']} = {i},{note}")
    out.append("};")
    out.append(f"inline constexpr uint32_t kProgramCount = {len(programs)};\n")
    base = descs[programs[0]["name"]]["metal_sizes_buffer"]
    out.append("// Naga's MSL gives every entry that uses a Storage or StorageReadWrite binding one more")
    out.append("// argument: a buffer at this Metal index holding one u32 per such binding of the program,")
    out.append("// in (group, binding) order, its byte size. The programs read it only for arrayLength,")
    out.append("// which none uses, but Metal expects a buffer bound there.")
    out.append(f"inline constexpr uint32_t kMetalSizesBuffer = {base};")
    out.append("static_assert(kMetalSizesBuffer < kMetalVertexBufferBase, \"below the vertex buffers\");\n")
    out.append("// A vertex input an entry reads: its location and the format of its shader type. A vertex")
    out.append("// layout may give a narrower format that converts to it, such as U8 for the break mask.")
    out.append("struct VertexInputDesc { const char* entry; uint8_t location; VertexFormat format; };")
    out.append("// A colour output a fragment entry writes: its location and the format of its target.")
    out.append("struct FragmentOutputDesc { const char* entry; uint8_t location; Format format; };")
    out.append("// A vertex and fragment entry that the compile checks pair into a pipeline.")
    out.append("struct PairDesc { const char* vertex; const char* fragment; };\n")
    for p in programs:
        d, c = descs[p["name"]], camel(p["name"])
        out.append(f"// ---- {p['name']}")
        out.append(f"inline constexpr EntryDesc k{c}Entries[] = {{")
        for e in d["entries"]:
            wg = ", ".join(str(x) for x in e["workgroup_size"]) if e["stage"] == "compute" else "1, 1, 1"
            out.append(f"    {{\"{e['name']}\", {STAGE[e['stage']]}, {{{wg}}}}},")
        out.append("};")
        if d["bindings"]:
            out.append(f"inline constexpr BindingDesc k{c}Bindings[] = {{")
            for b in d["bindings"]:
                stages = " | ".join(STAGE[s] for s in b["stages"])
                fmt = FORMAT[b["storage_format"]] if b["storage_format"] else "RGBA8Unorm"
                dyn = "true" if b["dynamic"] else "false"
                out.append(f"    {{{b['group']}, {b['binding']}, BindingType::{b['type']}, uint8_t({stages}), {dyn}, "
                           f"{b['size']}, Format::{fmt}, {b['msl_index']}}},  // {b['name']}")
            out.append("};")
        inputs = [(e["name"], i) for e in d["entries"] for i in e["inputs"]]
        if inputs:
            out.append(f"inline constexpr VertexInputDesc k{c}VertexInputs[] = {{")
            for name, i in inputs:
                out.append(f"    {{\"{name}\", {i['location']}, VertexFormat::{VERTEX_FORMAT[i['type']]}}},  // {i['type']}")
            out.append("};")
        outputs = [(e["name"], o) for e in d["entries"] for o in e["outputs"]]
        if outputs:
            out.append(f"inline constexpr FragmentOutputDesc k{c}FragmentOutputs[] = {{")
            for name, o in outputs:
                out.append(f"    {{\"{name}\", {o['location']}, Format::{OUTPUT_FORMAT[o['type']]}}},  // {o['type']}")
            out.append("};")
        if p["pairs"]:
            out.append(f"inline constexpr PairDesc k{c}Pairs[] = {{")
            for v, f in p["pairs"]:
                out.append(f"    {{\"{v}\", \"{f}\"}},")
            out.append("};")
        out.append("")
    out.append("// The descriptions by program id, with no sources, for code that needs no backend.")
    out.append("struct ProgramDescription {")
    out.append("    const char* name; const EntryDesc* entries; uint8_t entry_count;")
    out.append("    const BindingDesc* bindings; uint8_t binding_count;")
    out.append("    const VertexInputDesc* vertex_inputs; uint8_t vertex_input_count;")
    out.append("    const FragmentOutputDesc* fragment_outputs; uint8_t fragment_output_count;")
    out.append("    const PairDesc* pairs; uint8_t pair_count; bool test_only;")
    out.append("};")
    out.append("inline constexpr ProgramDescription kProgramDescriptions[kProgramCount] = {")
    for p in programs:
        d, c = descs[p["name"]], camel(p["name"])
        has_in = any(e["inputs"] for e in d["entries"])
        n_in = sum(len(e["inputs"]) for e in d["entries"])
        n_out = sum(len(e["outputs"]) for e in d["entries"])
        out.append(f"    {{\"{p['name']}\", k{c}Entries, {len(d['entries'])}, "
                   + (f"k{c}Bindings, {len(d['bindings'])}, " if d["bindings"] else "nullptr, 0, ")
                   + (f"k{c}VertexInputs, {n_in}, " if has_in else "nullptr, 0, ")
                   + (f"k{c}FragmentOutputs, {n_out}, " if n_out else "nullptr, 0, ")
                   + (f"k{c}Pairs, {len(p['pairs'])}, " if p["pairs"] else "nullptr, 0, ")
                   + ("true" if p.get("test_only") else "false") + "},")
    out.append("};\n")
    out.append(f"}}  // namespace {NAMESPACE}\n")
    return "\n".join(out)


def table_header(backend: str, programs: list[dict], version: str) -> str:
    kind = {"metal": "msl", "vulkan": "spirv", "webgpu": "wgsl"}[backend]
    out = [banner(None, version, f"The table of ProgramDescs for the {backend} backend, indexed by ProgramId."),
           "#pragma once\n", '#include "gfx/shaders/generated/programs.h"']
    for p in programs:
        hw = p["hand_written"].get(kind)
        out.append(f'#include "{hw}"' if hw else f'#include "gfx/shaders/generated/{p["name"]}_{kind_file(kind)}.h"')
    out.append(f"\nnamespace {NAMESPACE} {{\n")
    name = {"metal": "kMetalPrograms", "vulkan": "kVulkanPrograms", "webgpu": "kWebgpuPrograms"}[backend]
    out.append(f"inline constexpr ProgramDesc {name}[kProgramCount] = {{")
    for p in programs:
        c = camel(p["name"])
        src = {"msl": f"k{c}Msl", "wgsl": f"k{c}Wgsl", "spirv": f"k{c}Spirv"}[kind]
        wgsl = src if kind == "wgsl" else "nullptr"
        msl = src if kind == "msl" else "nullptr"
        spv = f"{src}, uint32_t(sizeof({src}))" if kind == "spirv" else "nullptr, 0"
        out.append(f"    {{\"{p['name']}\", kProgramDescriptions[{programs.index(p)}].entries, kProgramDescriptions[{programs.index(p)}].entry_count,")
        out.append(f"     kProgramDescriptions[{programs.index(p)}].bindings, kProgramDescriptions[{programs.index(p)}].binding_count, {wgsl}, {msl}, {spv}}},")
    out.append("};\n")
    out.append(f"}}  // namespace {NAMESPACE}\n")
    return "\n".join(out)


def kind_file(kind: str) -> str:
    return {"wgsl": "wgsl", "msl": "msl", "spirv": "spv"}[kind]


# ---- the run -------------------------------------------------------------------------------

def generate(driver: Path, out_dir: Path, work: Path) -> dict[str, bytes]:
    """Returns the generated files by name."""
    manifest = json.loads(MANIFEST.read_text())
    programs = manifest["programs"]
    version = naga_version()
    got = subprocess.run([str(driver), "--version"], capture_output=True, text=True, check=True).stdout
    if version not in got:
        raise Error(f"the driver reports {got.strip()!r}, but Cargo.lock pins naga {version}")
    files: dict[str, bytes] = {}
    descs: dict[str, dict] = {}
    blocks: dict[str, dict] = {}
    names = set()
    for p in programs:
        if p["name"] in names or not re.fullmatch(r"[a-z][a-z0-9_]*", p["name"]):
            raise Error(f"program name {p['name']!r} is repeated or not lowercase with underscores")
        names.add(p["name"])
        for k in p["outputs"]:
            if k not in OUTPUTS:
                raise Error(f"{p['name']}: unknown output {k}")
        for k, path in p["hand_written"].items():
            if k not in OUTPUTS or k in p["outputs"]:
                raise Error(f"{p['name']}: hand-written {k} must be a known output that is not generated")
            if not (REPO / "src" / "host" / path).exists():
                raise Error(f"{p['name']}: the hand-written {k}, src/host/{path}, does not exist")
        for k in OUTPUTS:
            if k not in p["outputs"] and k not in p["hand_written"]:
                raise Error(f"{p['name']}: {k} is neither generated nor hand-written")
        parts, starts, line = [], [], 1
        for s in p["sources"]:
            text = (SHADERS / s).read_text()
            if not text.endswith("\n"):
                raise Error(f"src/host/gfx/shaders/{s} does not end with a line break")
            parts.append(f"// ---- {s}\n" + text)
            starts.append((line + 1, s))   # the file's first line follows its marker line
            line += 2 + text.count("\n")  # the marker, the file and the joining line break
        wgsl = "\n".join(parts)
        src = work / f"{p['name']}.wgsl"
        src.write_text(wgsl)
        cmd = [str(driver), str(src), "--reflect", str(work / f"{p['name']}.json")]
        if "msl" in p["outputs"]:
            cmd += ["--msl", str(work / f"{p['name']}.metal")]
        if "spirv" in p["outputs"]:
            cmd += ["--spv", str(work / f"{p['name']}.spv")]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            def where(mt: re.Match) -> str:  # a line of the assembled program -> its source file's line
                n = int(mt.group(1))
                first, name = max((st for st in starts if st[0] <= n), default=(1, p["name"] + ".wgsl"))
                return f"src/host/gfx/shaders/{name}:{n - first + 1}:"
            msg = re.sub(re.escape(str(src)) + r":(\d+):", where, r.stderr)
            msg = re.sub(re.escape(src.name) + r":(\d+):", where, msg)
            raise Error(f"{p['name']} does not compile:\n{msg}")
        d = json.loads((work / f"{p['name']}.json").read_text())
        # Every uniform binding is dynamic: the frame, draw and colormap blocks and the compute
        # parameters all live in the uniform arena (gfx.h, decisions 6 and 7).
        for b in d["bindings"]:
            b["dynamic"] = b["type"] == "Uniform"
            if b["block"] is not None:
                prev = blocks.setdefault(b["block"]["name"], b["block"])
                if prev != b["block"]:
                    raise Error(f"the uniform block {b['block']['name']} has two layouts")
        dyn = sum(1 for b in d["bindings"] if b["dynamic"])
        if dyn > 4:
            raise Error(f"{p['name']}: {dyn} dynamic bindings, above gfx.h's kMaxDynamicOffsets")
        for g in {b["group"] for b in d["bindings"]}:
            if sum(1 for b in d["bindings"] if b["group"] == g) > 8 or g > 3:
                raise Error(f"{p['name']}: group {g} is past gfx.h's limits")
        entries = {e["name"]: e for e in d["entries"]}
        for v, f in p["pairs"]:
            if entries.get(v, {}).get("stage") != "vertex" or entries.get(f, {}).get("stage") != "fragment":
                raise Error(f"{p['name']}: pair ({v}, {f}) is not a vertex and a fragment entry")
        descs[p["name"]] = d
        c = p["name"]
        if "wgsl" in p["outputs"]:
            files[f"{c}_wgsl.h"] = source_header(p, version, "wgsl", wgsl).encode()
        if "msl" in p["outputs"]:
            files[f"{c}_msl.h"] = source_header(p, version, "msl", (work / f"{c}.metal").read_text()).encode()
        if "spirv" in p["outputs"]:
            raw = (work / f"{c}.spv").read_bytes()
            words = [int.from_bytes(raw[i:i + 4], "little") for i in range(0, len(raw), 4)]
            files[f"{c}_spv.h"] = source_header(p, version, "spirv", words).encode()

    structs: dict[str, str] = {}
    order: list[str] = []
    for block in blocks.values():
        struct_decl(block, structs, order)
    uni = [banner(None, version, "Every uniform block of the programs as a C++ struct, with its size and offsets checked."),
           "#pragma once\n", "#include <cstddef>", "#include <cstdint>\n", f"namespace {NAMESPACE} {{\n"]
    uni += [structs[n] for n in order]
    uni.append(f"}}  // namespace {NAMESPACE}\n")
    files["uniforms.h"] = "\n".join(uni).encode()
    files["programs.h"] = programs_header(programs, descs, version).encode()
    for backend in ("metal", "vulkan", "webgpu"):
        files[f"programs_{backend}.h"] = table_header(backend, programs, version).encode()
    listing = {"naga": version, "programs": []}
    for p in programs:
        d = descs[p["name"]]
        listing["programs"].append({
            "name": p["name"], "test_only": bool(p.get("test_only")), "sources": p["sources"],
            "outputs": p["outputs"], "hand_written": p["hand_written"], "pairs": p["pairs"],
            "msl_version": d["msl_version"], "spirv_version": d["spirv_version"],
            "metal_vertex_buffer_base": d["metal_vertex_buffer_base"],
            "bindings": [{k: v for k, v in b.items() if k != "block"} for b in d["bindings"]],
            "entries": d["entries"],
        })
    listing["uniforms"] = {n: blocks[n] for n in order if n in blocks}
    files["programs.json"] = (json.dumps(listing, indent=2) + "\n").encode()
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail when a generated file differs from what is committed")
    ap.add_argument("--driver", help="a built caliper-naga-driver (default: build it with cargo)")
    ap.add_argument("--root", help="the repository root to work on (default: this checkout)")
    args = ap.parse_args()
    if args.root:
        set_root(Path(args.root).resolve())
    try:
        driver = Path(args.driver) if args.driver else build_driver()
        with tempfile.TemporaryDirectory(prefix="caliper-shaders-") as tmp:
            files = generate(driver, GENERATED, Path(tmp))
        if args.check:
            bad = []
            for name, data in sorted(files.items()):
                path = GENERATED / name
                if not path.exists():
                    bad.append(f"missing: {name}")
                elif path.read_bytes() != data:
                    bad.append(f"differs: {name}")
            for path in sorted(GENERATED.iterdir()):
                if path.name not in files:
                    bad.append(f"not generated: {path.name}")
            if bad:
                print("The generated shader files are out of date; run tools/shaders/generate.py:", file=sys.stderr)
                print("\n".join("  " + b for b in bad), file=sys.stderr)
                return 1
            print(f"{len(files)} generated shader files match their sources (Naga {naga_version()}).")
            return 0
        GENERATED.mkdir(parents=True, exist_ok=True)
        for path in GENERATED.iterdir():
            if path.name not in files:
                path.unlink()
        for name, data in files.items():
            path = GENERATED / name
            if not path.exists() or path.read_bytes() != data:
                path.write_bytes(data)
        print(f"wrote {len(files)} files to src/host/gfx/shaders/generated (Naga {naga_version()}).")
        return 0
    except (Error, subprocess.CalledProcessError) as e:
        print(f"generate.py: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
