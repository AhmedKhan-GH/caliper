def render_colormap_coeffs_h(data: dict[str, Any]) -> str:
    by_name = {e["name"]: e for e in data["colormaps"]["entries"]}
    v_coeffs = by_name["viridis"]["coefficients"]
    m_coeffs = by_name["magma"]["coefficients"]
    rdbu = by_name["rdbu"]["anchors"]

    lines = [
        "// colormap_coeffs.h: polynomial coefficients and anchors for viridis, magma and rdbu.",
        "//",
        f"// {GEN_BANNER}",
        "#pragma once",
        "",
        "namespace caliper_gfx {",
        "namespace cmap {",
        "",
        "// viridis / magma: matplotlib-derived degree-6 polynomial fits (Matt Zucker,",
        "// https://www.shadertoy.com/view/WlfXRN) — accurate to <2/255 vs matplotlib.",
        "// Each row k holds the RGB coefficient of t^k for k = 0..6.",
        "inline constexpr float kViridisPoly[7][3] = {",
    ]
    for row in v_coeffs:
        lines.append(f"    {{{row[0]!r}f, {row[1]!r}f, {row[2]!r}f}},")
    lines += [
        "};",
        "",
        "inline constexpr float kMagmaPoly[7][3] = {",
    ]
    for row in m_coeffs:
        lines.append(f"    {{{row[0]!r}f, {row[1]!r}f, {row[2]!r}f}},")
    lines += [
        "};",
        "",
        "// RdBu: ColorBrewer 11-class diverging anchors (the same control points",
        "// matplotlib's RdBu is built from), piecewise-linear over t in [0,1].",
        "inline constexpr float kRdbuAnchors[11][3] = {",
    ]
    for row in rdbu:
        lines.append(f"    {{{row[0]}.0f, {row[1]}.0f, {row[2]}.0f}},")
    lines += [
        "};",
        "",
        "}  // namespace cmap",
        "}  // namespace caliper_gfx",
    ]
    return "\n".join(lines) + "\n"


def render_colormap_tables_h(data: dict[str, Any]) -> str:
    sources = data["colormaps"]["sources"]
    entries = data["colormaps"]["entries"]
    sampled = [e for e in entries if e["kind"] == "lut256"]

    lines = [
        "// colormap_tables.h: the built-in colormap tables of the graphics layer, ids 0 to 15.",
        "//",
        f"// {GEN_BANNER} Ids 0 to 2 (viridis, magma, rdbu)",
        "// come from caliper_host::colormap_lut, and id 3 (greys) is the grey ramp. Ids 4 to 15 are",
        "// the tables below, in the order of the spec's name table: "
        + ", ".join(e["name"] for e in sampled[:6]) + ",",
        "// " + ", ".join(e["name"] for e in sampled[6:]) + ".",
        "//",
        f"// Sources: cividis, inferno, plasma, turbo, twilight and coolwarm come from matplotlib {sources['matplotlib']}.",
        f"// batlow, vik, roma, oslo, lajolla and berlin come from the cmcrameri package {sources['cmcrameri']}, which",
        "// ships the Scientific Colour Maps. Each map is sampled at 256 evenly",
        "// spaced points, i / 255 for i in 0 to 255. Each channel is rounded to 8 bits with round",
        "// half to even. An entry packs r | g << 8 | b << 16 | 0xff << 24.",
        "#pragma once",
        "",
        '#include "gfx/colormap_ref.h"   // caliper_host::colormap_lut and CALIPER_CMAP_*',
        "",
        "#include <cstdint>",
        "",
        "namespace caliper_gfx {",
        "namespace cmap {",
        "",
        "// The number of built-in colormaps, ids 0 to kBuiltinColormaps - 1.",
        f"inline constexpr int kBuiltinColormaps = {len(entries)};",
        "",
    ]
    for e in sampled:
        lines.append(f"// Id {e['id']}, {e['name']}: 256 packed RGBA8 entries.")
        lines.append(f"inline constexpr uint32_t k_{e['name']}[256] = {{")
        vals = e["rgba8"]
        for r in range(0, 256, 8):
            lines.append("    " + ", ".join(vals[r:r + 8]) + ",")
        lines.append("};")
        lines.append("")
    lines += [
        "// The 256-entry table of a built-in colormap id, or nullptr for an id outside 0 to 15.",
        "// Ids 0 to 2 are the host's viridis, magma and rdbu, id 3 is greys, ids 4 to 15 are the",
        "// tables above.",
        "inline const uint32_t* builtin_lut(int32_t id) {",
        "    static const struct Greys {",
        "        uint32_t t[256];",
        "        Greys() { for (uint32_t i = 0; i < 256; ++i) t[i] = 0xff000000u | (i << 16) | (i << 8) | i; }",
        "    } greys;",
        "    switch (id) {",
        "        case 0: return caliper_host::colormap_lut(CALIPER_CMAP_VIRIDIS);",
        "        case 1: return caliper_host::colormap_lut(CALIPER_CMAP_MAGMA);",
        "        case 2: return caliper_host::colormap_lut(CALIPER_CMAP_RDBU);",
        "        case 3: return greys.t;",
    ]
    for e in sampled:
        lines.append(f"        case {e['id']}: return k_{e['name']};")
    lines += [
        "        default: return nullptr;",
        "    }",
        "}",
        "",
        "}  // namespace cmap",
        "}  // namespace caliper_gfx",
    ]
    return "\n".join(lines) + "\n"


def render_spec_colormaps_cpp(data: dict[str, Any]) -> str:
    names = [e["name"] for e in data["colormaps"]["entries"]]
    rows = []
    for i in range(0, len(names), 4):
        rows.append("        " + ", ".join(f'"{n}"' for n in names[i:i + 4]) + ",")
    lines = [
        "// The colormap names of the format (colormaps.h).",
        f"// {GEN_BANNER}",
        "#include <caliper_builder/spec/colormaps.h>",
        "",
        "namespace caliper_builder::spec {",
        "",
        "const std::vector<std::string>& colormap_names() {",
        "    // The sixteen names, in id order. The graphics layer holds the color table",
        "    // of each id (src/host/gfx/colormap_tables.h), so a name never exists",
        "    // without its colors.",
        "    static const std::vector<std::string> names = {",
        *rows,
        "    };",
        "    return names;",
        "}",
        "",
        "std::optional<int> colormap_id(std::string_view name) {",
        "    const std::vector<std::string>& names = colormap_names();",
        "    for (std::size_t i = 0; i < names.size(); ++i)",
        "        if (names[i] == name) return static_cast<int>(i);",
        "    return std::nullopt;",
        "}",
        "",
        "}  // namespace caliper_builder::spec",
    ]
    return "\n".join(lines) + "\n"


def render_sternbild_theme_colors_inc(data: dict[str, Any]) -> str:
    tokens = data["theme"]["tokens"]
    untok = data["theme"]["untokenized"]
    role_tokens = [t for t in tokens if t["group"] == "role"]
    data_tokens = [t for t in tokens if t["group"] == "data"]

    lines = [
        f"// {GEN_BANNER}",
        "// Included inside namespace sternbild::col in src/host/ui/sternbild_theme.h.",
        "",
    ]
    role_width = max(len(t["name"]) for t in role_tokens)
    for t in role_tokens:
        lines.append(f"constexpr ImU32 {t['name']:<{role_width}} = tokens::{t['group']}::{t['token']}.imu32;")
    lines += [
        "",
        "// Plot class pigments (data colours of the tokens). Data only, never chrome; fixed order.",
    ]
    data_width = max(len(t["name"]) for t in data_tokens)
    for t in data_tokens:
        lines.append(f"constexpr ImU32 {t['name']:<{data_width}} = tokens::{t['group']}::{t['token']}.imu32;")
    lines += [
        "",
        "// BEGIN colours without a token",
        "// Colours the app draws that the design tokens do not cover. Each one is",
        "// Caliper's own constant; a token that names the same role replaces it here.",
    ]
    untok_width = max(len(u["name"]) for u in untok)
    for u in untok:
        r, g, b, a = u["rgba"]
        lines.append(f"constexpr ImU32 {u['name']:<{untok_width}} = IM_COL32({r}, {g}, {b}, {a});")
        if u["name"] == "hover_ring":
            lines.append("// A scrim or shadow: black at an alpha, under labels and over pictures.")
            lines.append("constexpr ImU32 shade(int alpha) { return IM_COL32(0, 0, 0, alpha); }")
    lines.append("// END colours without a token")
    return "\n".join(lines) + "\n"


def render_scene_palette_h(data: dict[str, Any]) -> str:
    untok = {u["name"]: u["rgba"] for u in data["theme"]["untokenized"]}
    fr, fg, fb, _ = untok["flat_point"]
    pal = data["categorical_palette"]
    lines = [
        "// scene_palette.h: categorical palette and default point colour of the scene core.",
        f"// {GEN_BANNER}",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace caliper_scene {",
        "namespace detail {",
        "",
        "inline constexpr uint32_t pack_rgb(uint32_t r, uint32_t g, uint32_t b) {",
        "    return 0xff000000u | (b << 16) | (g << 8) | r;",
        "}",
        "",
        f"inline constexpr uint32_t kFlatPointRgba = pack_rgb({fr}, {fg}, {fb});",
        "",
        "}  // namespace detail",
        "}  // namespace caliper_scene",
        "",
        "#define CALIPER_SCENE_PALETTE_INIT { \\",
    ]
    for i in range(0, len(pal), 4):
        chunk = ", ".join(f"::caliper_scene::detail::pack_rgb({r}, {g}, {b})" for r, g, b in pal[i:i + 4])
        lines.append(f"    {chunk}, \\")
    lines.append("}")
    return "\n".join(lines) + "\n"


