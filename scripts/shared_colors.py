#!/usr/bin/env python3
"""Generate and check C++, TypeScript, and Python colormap and theme copies.

One source file, scripts/shared_colors.json, holds the 16 built-in colormaps,
the Sternbild theme token bindings, the untokenized Caliper house colours,
and the 16-colour categorical palette.

Usage:
    python3 scripts/shared_colors.py --check [--root <repo>]
    python3 scripts/shared_colors.py --write [--root <repo>]
    python3 scripts/shared_colors.py --resample-colormaps [--root <repo>]

Generation and checking use only the Python 3 standard library.
--resample-colormaps is an optional maintainer mode that imports numpy,
matplotlib, and cmcrameri to resample colormaps 4 to 15 into shared_colors.json.

Exit status: 0 when all copies match (or after --write), 1 on drift, 2 on bad input.
"""
