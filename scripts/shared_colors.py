def _f32(x: float) -> float:
    return struct.unpack("<f", struct.pack("<f", x))[0]


def _pack_rgba_float(r: float, g: float, b: float) -> int:
    def q(x: float) -> int:
        v = _f32(x)
        if v < 0.0:
            v = 0.0
        elif v > 1.0:
            v = 1.0
        return int(_f32(_f32(v * _f32(255.0)) + _f32(0.5)))

    return q(r) | (q(g) << 8) | (q(b) << 16) | (0xFF << 24)


def _eval_poly6_lut(coeffs: list[list[float]]) -> list[int]:
    """Evaluate a degree-6 RGB polynomial in float32, matching tensor_bridge.cpp."""
    lut: list[int] = []
    c = [[_f32(v) for v in row] for row in coeffs]
    f255 = _f32(255.0)
    f1 = _f32(1.0)
    for i in range(256):
        t = _f32(_f32(float(i)) / f255)
        r, g, b = c[0][0], c[0][1], c[0][2]
        tp = f1
        for k in range(1, 7):
            tp = _f32(tp * t)
            r = _f32(r + _f32(c[k][0] * tp))
            g = _f32(g + _f32(c[k][1] * tp))
            b = _f32(b + _f32(c[k][2] * tp))
        lut.append(_pack_rgba_float(r, g, b))
    return lut


def _eval_anchors_lut(anchors: list[list[int]]) -> list[int]:
    """Evaluate piecewise-linear RGB anchors in float32, matching tensor_bridge.cpp."""
    lut: list[int] = []
    a = [[_f32(float(v)) for v in row] for row in anchors]
    f255 = _f32(255.0)
    f10 = _f32(float(len(a) - 1))
    max_lo = len(a) - 2
    for i in range(256):
        p = _f32(_f32(_f32(float(i)) / f255) * f10)
        lo = min(int(p), max_lo)
        fr = _f32(p - _f32(float(lo)))
        r = _f32(_f32(a[lo][0] + _f32(_f32(a[lo + 1][0] - a[lo][0]) * fr)) / f255)
        g = _f32(_f32(a[lo][1] + _f32(_f32(a[lo + 1][1] - a[lo][1]) * fr)) / f255)
        b = _f32(_f32(a[lo][2] + _f32(_f32(a[lo + 1][2] - a[lo][2]) * fr)) / f255)
        lut.append(_pack_rgba_float(r, g, b))
    return lut


def compute_lut(entry: dict[str, Any]) -> list[int]:
    """Return the 256 packed RGBA8 uint32 entries for a colormap entry."""
    kind = entry["kind"]
    if kind == "poly6":
        return _eval_poly6_lut(entry["coefficients"])
    if kind == "anchors_rgb":
        return _eval_anchors_lut(entry["anchors"])
    if kind == "grey_ramp":
        return [0xFF000000 | (i << 16) | (i << 8) | i for i in range(256)]
    if kind == "lut256":
        return [int(h, 16) for h in entry["rgba8"]]
    raise ValueError(f"unknown colormap kind: {kind!r}")


def load_definitions(root: pathlib.Path) -> dict[str, Any]:
    path = root / SOURCE_REL
    if not path.is_file():
        raise FileNotFoundError(f"missing source definitions file: {SOURCE_REL}")
    data = json.loads(path.read_text(encoding="utf-8"))
    validate_definitions(data)
    return data


def validate_definitions(data: dict[str, Any]) -> None:
    entries = data["colormaps"]["entries"]
    if len(entries) != 16:
        raise ValueError(f"expected 16 colormaps, got {len(entries)}")
    for idx, entry in enumerate(entries):
        if entry["id"] != idx:
            raise ValueError(f"colormap {entry['name']} has id {entry['id']}, expected {idx}")
        if entry["kind"] == "poly6":
            coeffs = entry["coefficients"]
            if len(coeffs) != 7 or any(len(row) != 3 for row in coeffs):
                raise ValueError(f"colormap {entry['name']} must have 7x3 coefficients")
        elif entry["kind"] == "anchors_rgb":
            anchors = entry["anchors"]
            if len(anchors) != 11 or any(len(row) != 3 for row in anchors):
                raise ValueError(f"colormap {entry['name']} must have 11x3 anchors")
        elif entry["kind"] == "lut256":
            rgba8 = entry["rgba8"]
            if len(rgba8) != 256:
                raise ValueError(f"colormap {entry['name']} must have 256 rgba8 entries")
    tokens = data["theme"]["tokens"]
    token_names = {t["name"] for t in tokens}
    for pigment in data["theme"]["house_pigments"]:
        if pigment not in token_names:
            raise ValueError(f"house pigment {pigment!r} missing from theme.tokens")
    if len(data["categorical_palette"]) != 16:
        raise ValueError("categorical_palette must have 16 RGB entries")


def _replace_marked_block(existing: str, begin: str, end: str, body: str, rel: str) -> str:
    pattern = re.compile(
        r"(" + re.escape(begin) + r"\n).*?(" + re.escape(end) + r")",
        re.DOTALL,
    )
    if not pattern.search(existing):
        raise ValueError(f"{rel} is missing markers {begin!r} ... {end!r}")
    return pattern.sub(lambda m: m.group(1) + body + m.group(2), existing, count=1)


