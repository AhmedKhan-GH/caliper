def render_palette_gen_ts(data: dict[str, Any]) -> str:
    tokens = data["theme"]["tokens"]
    by_name = {t["name"]: t["rgb"] for t in tokens}
    house = [by_name[n] for n in data["theme"]["house_pigments"]]
    cat = data["categorical_palette"]

    def rgb(c: list[int]) -> str:
        return f"[{c[0]}, {c[1]}, {c[2]}]"

    lines = [
        f"// {GEN_BANNER}",
        "// The app draws with these constants, and the page with this table.",
        "",
        "export type Rgb = readonly [number, number, number];",
        "",
        "/** The house's colour tokens (sternbild::col), by their C++ names. */",
        "export const TOKENS: Readonly<Record<string, Rgb>> = {",
        *[f"  {t['name']}: {rgb(t['rgb'])}," for t in tokens],
        "};",
        "",
        "/** The class pigments in their fixed order: vehicle, dog, bird, cat, other. */",
        f"export const HOUSE_PIGMENTS: readonly Rgb[] = [{', '.join(rgb(c) for c in house)}];",
        "",
        "/** The live views' categorical palette (caliper_scene::kPalette), 16 colours. */",
        "export const CATEGORICAL: readonly Rgb[] = [",
        *[f"  {', '.join(rgb(c) for c in cat[i:i + 4])}," for i in range(0, 16, 4)],
        "];",
    ]
    return "\n".join(lines) + "\n"


def render_colormaps_gen_ts(data: dict[str, Any]) -> str:
    entries = data["colormaps"]["entries"]
    by_name = {e["name"]: e for e in entries}
    v_coeffs = by_name["viridis"]["coefficients"]
    m_coeffs = by_name["magma"]["coefficients"]
    rdbu = by_name["rdbu"]["anchors"]
    rdbu_flat = [x for row in rdbu for x in row]
    names = [e["name"] for e in entries]
    sampled = [e for e in entries if e["kind"] == "lut256"]
    untok = {u["name"]: u["rgba"] for u in data["theme"]["untokenized"]}
    flat = untok["flat_point"][:3]

    lines = [
        f"// {GEN_BANNER}",
        "// All 16 built-in colormaps (ids 0 to 15), matching src/host/gfx/colormap_tables.h.",
        "",
        "import type { Rgb } from './palette.gen.js';",
        "",
        "const f = Math.fround;",
        "",
        "// Quantizes one channel the way pack_rgba does: clamp to [0, 1], then",
        "// (uint32_t)(x * 255.0f + 0.5f) in float32.",
        "function q(x: number): number {",
        "  let v = f(x);",
        "  if (v < 0) v = 0;",
        "  if (v > 1) v = 1;",
        "  return Math.trunc(f(f(v * 255) + 0.5));",
        "}",
        "",
        "// viridis and magma: degree-6 polynomial fits to matplotlib's tables; c[k] is",
        "// the RGB coefficient of t^k. Evaluated in float32 like gen_poly.",
        "const VIRIDIS: readonly number[] = [",
        *[f"  {row[0]!r}, {row[1]!r}, {row[2]!r}," for row in v_coeffs],
        "];",
        "const MAGMA: readonly number[] = [",
        *[f"  {row[0]!r}, {row[1]!r}, {row[2]!r}," for row in m_coeffs],
        "];",
        "// RdBu: the ColorBrewer 11-class anchors, piecewise linear.",
        "const RDBU: readonly number[] = [",
        "  " + ", ".join(str(x) for x in rdbu_flat[:18]) + ",",
        "  " + ", ".join(str(x) for x in rdbu_flat[18:]) + ",",
        "];",
        "",
        "function polyLut(c: readonly number[]): Uint8Array {",
        "  const out = new Uint8Array(256 * 4);",
        "  for (let i = 0; i < 256; i++) {",
        "    const t = f(i / 255);",
        "    let r = f(c[0]), g = f(c[1]), b = f(c[2]), tp = f(1);",
        "    for (let k = 1; k < 7; k++) {",
        "      tp = f(tp * t);",
        "      r = f(r + f(f(c[3 * k]) * tp));",
        "      g = f(g + f(f(c[3 * k + 1]) * tp));",
        "      b = f(b + f(f(c[3 * k + 2]) * tp));",
        "    }",
        "    out.set([q(r), q(g), q(b), 255], i * 4);",
        "  }",
        "  return out;",
        "}",
        "",
        "function rdbuLut(): Uint8Array {",
        "  const out = new Uint8Array(256 * 4);",
        "  for (let i = 0; i < 256; i++) {",
        "    const p = f(f(i / 255) * 10);",
        "    let lo = Math.trunc(p);",
        "    if (lo > 9) lo = 9;",
        "    const fr = f(p - lo);",
        "    const ch = (k: number) => {",
        "      const a = RDBU[lo * 3 + k], b = RDBU[(lo + 1) * 3 + k];",
        "      return f(f(a + f(f(b - a) * fr)) / 255);",
        "    };",
        "    out.set([q(ch(0)), q(ch(1)), q(ch(2)), 255], i * 4);",
        "  }",
        "  return out;",
        "}",
        "",
        "/** Default colour of points without per-item colour (sternbild::col::flat_point). */",
        f"export const FLAT_POINT: Rgb = [{flat[0]}, {flat[1]}, {flat[2]}];",
        "",
        "export const SPEC_COLORMAP_NAMES = [",
        "  " + ", ".join(f"'{n}'" for n in names[:8]) + ",",
        "  " + ", ".join(f"'{n}'" for n in names[8:]) + ",",
        "] as const;",
        "",
        "export type SpecColormapName = (typeof SPEC_COLORMAP_NAMES)[number];",
        "",
        "const SPEC_COLORMAP_SET: ReadonlySet<string> = new Set(SPEC_COLORMAP_NAMES);",
        "",
        "export function isSpecColormapName(name: string | undefined): name is SpecColormapName {",
        "  return name !== undefined && SPEC_COLORMAP_SET.has(name);",
        "}",
        "",
        "// Sampled 256-entry RGB tables (ids 4 to 15), base64-encoded 768 RGB bytes each.",
        "const SAMPLED_RGB_B64: Readonly<Record<string, string>> = {",
    ]
    for e in sampled:
        rgb_bytes = bytearray(256 * 3)
        for i, h in enumerate(e["rgba8"]):
            v = int(h, 16)
            rgb_bytes[i * 3] = v & 0xFF
            rgb_bytes[i * 3 + 1] = (v >> 8) & 0xFF
            rgb_bytes[i * 3 + 2] = (v >> 16) & 0xFF
        b64 = base64.b64encode(bytes(rgb_bytes)).decode("ascii")
        lines.append(f"  {e['name']}: '{b64}',")
    lines += [
        "};",
        "",
        "const specCache = new Map<string, Uint8Array>();",
        "",
        "function decodeRgbB64(b64: string): Uint8Array {",
        "  const bin = atob(b64);",
        "  const out = new Uint8Array(256 * 4);",
        "  for (let i = 0; i < 256; i++) {",
        "    const s = i * 3;",
        "    const d = i * 4;",
        "    out[d] = bin.charCodeAt(s);",
        "    out[d + 1] = bin.charCodeAt(s + 1);",
        "    out[d + 2] = bin.charCodeAt(s + 2);",
        "    out[d + 3] = 255;",
        "  }",
        "  return out;",
        "}",
        "",
        "/** The 256-entry RGBA table of any of the 16 built-in colormaps. */",
        "export function specColormapLut(name: SpecColormapName): Uint8Array {",
        "  let table = specCache.get(name);",
        "  if (table) return table;",
        "  if (name === 'viridis') {",
        "    table = polyLut(VIRIDIS);",
        "  } else if (name === 'magma') {",
        "    table = polyLut(MAGMA);",
        "  } else if (name === 'rdbu') {",
        "    table = rdbuLut();",
        "  } else if (name === 'greys') {",
        "    table = new Uint8Array(256 * 4);",
        "    for (let i = 0; i < 256; i++) table.set([i, i, i, 255], i * 4);",
        "  } else {",
        "    table = decodeRgbB64(SAMPLED_RGB_B64[name]);",
        "  }",
        "  specCache.set(name, table);",
        "  return table;",
        "}",
    ]
    return "\n".join(lines) + "\n"


