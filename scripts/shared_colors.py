def check_sternbild_pin(root: pathlib.Path, data: dict[str, Any]) -> list[str]:
    cmake_path = root / STERNBILD_CMAKE_REL
    if not cmake_path.is_file():
        return [f"{STERNBILD_CMAKE_REL}: file is missing"]
    text = cmake_path.read_text(encoding="utf-8")
    tag_m = re.search(r"set\(STERNBILD_TOKENS_TAG\s+([^\s)]+)\)", text)
    commit_m = re.search(r"set\(STERNBILD_TOKENS_COMMIT\s+([0-9a-f]{40})\)", text)
    if not tag_m or not commit_m:
        return [f"{STERNBILD_CMAKE_REL}: missing STERNBILD_TOKENS_TAG or STERNBILD_TOKENS_COMMIT"]
    want = data["sternbild_tokens"]
    issues: list[str] = []
    if tag_m.group(1) != want["tag"]:
        issues.append(
            f"{STERNBILD_CMAKE_REL}: STERNBILD_TOKENS_TAG is {tag_m.group(1)!r}, "
            f"shared_colors.json has {want['tag']!r}"
        )
    if commit_m.group(1) != want["commit"]:
        issues.append(
            f"{STERNBILD_CMAKE_REL}: STERNBILD_TOKENS_COMMIT is {commit_m.group(1)!r}, "
            f"shared_colors.json has {want['commit']!r}"
        )
    return issues


def render_all(root: pathlib.Path, data: dict[str, Any]) -> dict[str, str]:
    outputs: dict[str, str] = {}
    for rel, fn in FULL_TARGETS:
        outputs[rel] = fn(data)
    for rel, begin, end, fn in BLOCK_TARGETS:
        path = root / rel
        if not path.is_file():
            raise FileNotFoundError(f"missing managed target: {rel}")
        existing = path.read_text(encoding="utf-8")
        outputs[rel] = _replace_marked_block(existing, begin, end, fn(data), rel)
    return outputs


def check_files(root: pathlib.Path) -> list[str]:
    data = load_definitions(root)
    issues = check_sternbild_pin(root, data)
    for rel, fn in FULL_TARGETS:
        path = root / rel
        if not path.is_file():
            issues.append(f"{rel}: generated file is missing")
            continue
        actual = path.read_text(encoding="utf-8")
        expected = fn(data)
        if actual != expected:
            issues.append(f"{rel}: drifted from {SOURCE_REL}")
    for rel, begin, end, fn in BLOCK_TARGETS:
        path = root / rel
        if not path.is_file():
            issues.append(f"{rel}: managed file is missing")
            continue
        actual = path.read_text(encoding="utf-8")
        try:
            expected = _replace_marked_block(actual, begin, end, fn(data), rel)
        except ValueError as exc:
            issues.append(str(exc))
            continue
        if actual != expected:
            issues.append(f"{rel}: generated block drifted from {SOURCE_REL}")
    return issues


def write_files(root: pathlib.Path) -> list[str]:
    data = load_definitions(root)
    outputs = render_all(root, data)
    changed: list[str] = []
    for rel, content in outputs.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8", newline="\n")
            changed.append(rel)
    return changed


def format_source_json(data: dict[str, Any]) -> str:
    entries = data["colormaps"]["entries"]
    tokens = data["theme"]["tokens"]
    untok = data["theme"]["untokenized"]
    cat = data["categorical_palette"]
    sources = data["colormaps"]["sources"]
    pin = data["sternbild_tokens"]

    lines = ["{"]
    lines.append(f'  "schema_version": {data["schema_version"]},')
    lines.append('  "sternbild_tokens": {')
    lines.append(f'    "tag": {json.dumps(pin["tag"])},')
    lines.append(f'    "commit": {json.dumps(pin["commit"])}')
    lines.append("  },")
    lines.append('  "colormaps": {')
    lines.append('    "sources": {')
    lines.append(f'      "matplotlib": {json.dumps(sources["matplotlib"])},')
    lines.append(f'      "cmcrameri": {json.dumps(sources["cmcrameri"])}')
    lines.append("    },")
    lines.append('    "entries": [')
    for idx, e in enumerate(entries):
        comma = "," if idx + 1 < len(entries) else ""
        lines.append("      {")
        lines.append(f'        "id": {e["id"]},')
        lines.append(f'        "name": {json.dumps(e["name"])},')
        lines.append(f'        "live_wire_v3": {json.dumps(e["live_wire_v3"])},')
        if e["kind"] == "poly6":
            lines.append('        "kind": "poly6",')
            lines.append('        "coefficients": [')
            for ri, row in enumerate(e["coefficients"]):
                rc = "," if ri + 1 < len(e["coefficients"]) else ""
                lines.append(f"          [{row[0]!r}, {row[1]!r}, {row[2]!r}]{rc}")
            lines.append("        ]")
        elif e["kind"] == "anchors_rgb":
            lines.append('        "kind": "anchors_rgb",')
            lines.append('        "anchors": [')
            for ri, row in enumerate(e["anchors"]):
                rc = "," if ri + 1 < len(e["anchors"]) else ""
                lines.append(f"          [{row[0]}, {row[1]}, {row[2]}]{rc}")
            lines.append("        ]")
        elif e["kind"] == "grey_ramp":
            lines.append('        "kind": "grey_ramp"')
        else:
            lines.append('        "kind": "lut256",')
            lines.append(f'        "source": {json.dumps(e["source"])},')
            lines.append('        "rgba8": [')
            h = e["rgba8"]
            for r in range(0, 256, 8):
                chunk = ", ".join(json.dumps(v) for v in h[r:r + 8])
                rc = "," if r + 8 < 256 else ""
                lines.append(f"          {chunk}{rc}")
            lines.append("        ]")
        lines.append(f"      }}{comma}")
    lines.append("    ]")
    lines.append("  },")
    lines.append('  "theme": {')
    lines.append('    "tokens": [')
    for i, t in enumerate(tokens):
        c = "," if i + 1 < len(tokens) else ""
        lines.append(
            f'      {{"name": {json.dumps(t["name"])}, "group": {json.dumps(t["group"])}, '
            f'"token": {json.dumps(t["token"])}, "rgb": {json.dumps(t["rgb"])}}}{c}'
        )
    lines.append("    ],")
    lines.append(f'    "house_pigments": {json.dumps(data["theme"]["house_pigments"])},')
    lines.append('    "untokenized": [')
    for i, u in enumerate(untok):
        c = "," if i + 1 < len(untok) else ""
        lines.append(f'      {{"name": {json.dumps(u["name"])}, "rgba": {json.dumps(u["rgba"])}}}{c}')
    lines.append("    ]")
    lines.append("  },")
    lines.append('  "categorical_palette": [')
    for i, rgb in enumerate(cat):
        c = "," if i + 1 < len(cat) else ""
        lines.append(f"    {json.dumps(rgb)}{c}")
    lines.append("  ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def resample_colormaps(root: pathlib.Path) -> None:
    """Optional maintainer mode: resample ids 4..15 from matplotlib and cmcrameri."""
    import cmcrameri  # type: ignore[import-not-found]
    import matplotlib  # type: ignore[import-not-found]
    import numpy as np  # type: ignore[import-not-found]
    from cmcrameri import cm as crameri  # type: ignore[import-not-found]
    from matplotlib import colormaps as mpl_maps  # type: ignore[import-not-found]

    data = load_definitions(root)
    data["colormaps"]["sources"] = {
        "matplotlib": matplotlib.__version__,
        "cmcrameri": cmcrameri.__version__,
    }
    for e in data["colormaps"]["entries"]:
        if e["kind"] != "lut256":
            continue
        cmap = mpl_maps[e["name"]] if e["source"] == "matplotlib" else getattr(crameri, e["name"])
        rgb = np.asarray(cmap(np.arange(256) / 255.0))[:, :3]
        b = np.rint(rgb * 255.0).astype(np.uint32)
        e["rgba8"] = [f"0x{int(r | (g << 8) | (bl << 16) | (0xFF << 24)):08x}" for r, g, bl in b]
    (root / SOURCE_REL).write_text(format_source_json(data), encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--root",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parent.parent,
        help="repository root (default: parent of scripts/)",
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail when any generated copy drifted")
    mode.add_argument("--write", action="store_true", help="write all generated copies")
    mode.add_argument(
        "--resample-colormaps",
        action="store_true",
        help="resample ids 4..15 with matplotlib and cmcrameri, then write all copies",
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()

    try:
        if args.resample_colormaps:
            resample_colormaps(root)
            changed = write_files(root)
            print(f"Resampled colormaps and updated {len(changed)} generated file(s).")
            return 0
        if args.write:
            changed = write_files(root)
            if changed:
                print(f"Updated {len(changed)} file(s): {', '.join(changed)}")
            else:
                print("All generated colour and colormap files are already up to date.")
            return 0
        issues = check_files(root)
    except (FileNotFoundError, ValueError, json.JSONDecodeError) as exc:
        print(f"shared_colors: {exc}", file=sys.stderr)
        return 2

    if issues:
        for issue in issues:
            print(f"shared_colors: {issue}", file=sys.stderr)
        print(
            "Run `python3 scripts/shared_colors.py --write` to regenerate the copies.",
            file=sys.stderr,
        )
        return 1
    total = len(FULL_TARGETS) + len(BLOCK_TARGETS)
    print(f"All shared colour and colormap copies match {SOURCE_REL} ({total} files checked).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
